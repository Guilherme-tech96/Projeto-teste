// Generates the dotted world map used by the Global Network section.
// Run with `npm run generate:map` — output is committed, so this only
// needs to be re-run when changing the grid resolution or map bounds.
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const topology = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)),
);
const land = feature(topology, topology.objects.land);

// Keep in sync with lib/geo.ts
const MAP = { width: 1000, latTop: 80, latBottom: -58 };
const height = Math.round((MAP.width * (MAP.latTop - MAP.latBottom)) / 360);
const STEP = 2.25; // degrees between dots

const commands = [];
for (let lat = MAP.latTop - STEP / 2; lat > MAP.latBottom; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (!geoContains(land, [lon, lat])) continue;
    const x = ((lon + 180) / 360) * MAP.width;
    const y = ((MAP.latTop - lat) / (MAP.latTop - MAP.latBottom)) * height;
    commands.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}

const out = `// Auto-generated by scripts/generate-world-dots.mjs — do not edit by hand.
export const WORLD_DOTS_PATH =
  "${commands.join("")}";
export const WORLD_DOTS_COUNT = ${commands.length};
`;
writeFileSync(new URL("../lib/world-dots.ts", import.meta.url), out);
console.log(`Wrote ${commands.length} dots (${MAP.width}x${height})`);
